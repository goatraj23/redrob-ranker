#!/usr/bin/env python3
"""
Offline evaluation harness.

Ranks the labelled seed candidates with the production model and reports the
same metrics the organisers use (NDCG@10, NDCG@50, MAP, P@10, composite), plus
a honeypot-leakage check on the predicted top.

When a second, headline-only label set is present (`eval/seed_labels_headline.jsonl`,
generated by `tools/make_seed_labels_headline.py`), this script also runs the
ranker against it as a cross-lens integrity check — high metrics on the first
label set could be self-validating (the ranker and the rubric share a lens), so
a second rubric built from headline + summary only is the more honest test.

    python3 eval/run_eval.py --candidates ./candidates.jsonl
"""
from __future__ import annotations
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from redrob_ranker import features as F, scoring         # noqa: E402
from redrob_ranker.io_utils import stream_candidates       # noqa: E402
import metrics                                              # noqa: E402  (same dir)


def load_labels(path):
    out = {}
    with open(path) as fh:
        for line in fh:
            if line.strip():
                r = json.loads(line)
                out[r["candidate_id"]] = r
    return out


def score_pool(candidates_path, want):
    scored = []
    for c in stream_candidates(candidates_path):
        cid = c.get("candidate_id")
        if cid in want:
            feats = F.extract(c)
            info = scoring.score_candidate(c, feats, scoring.DEFAULT_WEIGHTS)
            scored.append((info["score"], cid, info))
            if len(scored) == len(want):
                break
    scored.sort(key=lambda x: (-x[0], x[1]))
    return scored


def report(label_set_name, scored, labels):
    rels = [labels[cid]["relevance"] for _, cid, _ in scored]
    m = metrics.composite(rels)
    hp_top10 = sum(1 for _, _, info in scored[:10] if info["is_honeypot"])

    print(f"\nEvaluated {len(scored)} labelled candidates against `{label_set_name}`:\n")
    print(f"  NDCG@10 : {m['ndcg@10']:.4f}")
    print(f"  NDCG@50 : {m['ndcg@50']:.4f}")
    print(f"  MAP     : {m['map']:.4f}")
    print(f"  P@10    : {m['p@10']:.4f}")
    print(f"  -----------------------------")
    print(f"  COMPOSITE: {m['composite']:.4f}   (0.5*N@10 + 0.3*N@50 + 0.15*MAP + 0.05*P@10)\n")
    print(f"  Honeypots in predicted top-10 of labelled set: {hp_top10}")
    print("\n  Predicted order (top 12):")
    for i, (s, cid, info) in enumerate(scored[:12], 1):
        flag = " [HONEYPOT]" if info["is_honeypot"] else ""
        title = labels[cid].get("title", "?")
        rel = labels[cid]["relevance"]
        print(f"   {i:2d}. rel={rel}  score={s:.3f}  {title}{flag}")
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidates", required=True)
    ap.add_argument("--labels", default="eval/seed_labels.jsonl")
    ap.add_argument("--labels_headline", default="eval/seed_labels_headline.jsonl")
    args = ap.parse_args()

    lab1 = load_labels(args.labels)
    lab2 = load_labels(args.labels_headline) if os.path.exists(args.labels_headline) else None
    want = set(lab1) | (set(lab2) if lab2 else set())

    print(f"Loaded {len(lab1)} career-history labels"
          + (f" + {len(lab2)} headline-only labels  (union {len(want)} candidates)."
             if lab2 else "."))

    scored_all = score_pool(args.candidates, want)
    by_id = {cid: (s, cid, info) for s, cid, info in scored_all}

    scored1 = sorted((by_id[cid] for cid in lab1 if cid in by_id),
                     key=lambda x: (-x[0], x[1]))
    m1 = report("career-history labels", scored1, lab1)

    if lab2:
        scored2 = sorted((by_id[cid] for cid in lab2 if cid in by_id),
                         key=lambda x: (-x[0], x[1]))
        m2 = report("headline-only labels (cross-lens check)", scored2, lab2)

        print("\n=== Summary ===")
        print(f"  {'Label set':<35}  NDCG@10  NDCG@50    MAP    P@10   COMPOSITE")
        print(f"  {'career-history':<35}  {m1['ndcg@10']:.4f}   {m1['ndcg@50']:.4f}  "
              f"{m1['map']:.4f}  {m1['p@10']:.4f}   {m1['composite']:.4f}")
        print(f"  {'headline-only (cross-lens)':<35}  {m2['ndcg@10']:.4f}   {m2['ndcg@50']:.4f}  "
              f"{m2['map']:.4f}  {m2['p@10']:.4f}   {m2['composite']:.4f}")


if __name__ == "__main__":
    main()
